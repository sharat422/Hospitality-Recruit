"""Deterministic workforce roster validation and notification helpers."""

from __future__ import annotations

from datetime import date, datetime, timedelta
from typing import Any

ACTIVE_ASSIGNMENT_STATUSES = {"ASSIGNED", "PUBLISHED", "CONFIRMED"}


def _dt(value: str | datetime) -> datetime:
    return value if isinstance(value, datetime) else datetime.fromisoformat(str(value).replace("Z", "+00:00"))


def _minutes(start: datetime, end: datetime, break_minutes: int = 0) -> int:
    return max(0, int((end - start).total_seconds() // 60) - int(break_minutes or 0))


def validate_shift_assignment(
    *, employee_id: str, start: str | datetime, end: str | datetime,
    existing_shifts: list[dict[str, Any]], availability: list[dict[str, Any]] | None = None,
    weekly_offs: list[dict[str, Any]] | None = None, approved_leave_dates: list[str | date] | None = None,
    break_minutes: int = 0, exclude_assignment_id: str | None = None,
    min_rest_hours: int = 12, max_weekly_minutes: int = 2880,
) -> dict[str, Any]:
    """Return every blocking conflict; never delegates hiring decisions to AI."""
    start_dt, end_dt = _dt(start), _dt(end)
    if end_dt <= start_dt:
        return {"valid": False, "conflicts": [{"code": "INVALID_RANGE", "message": "Shift end must be after start"}]}
    conflicts: list[dict[str, str]] = []
    week_start = start_dt.date() - timedelta(days=start_dt.isoweekday() - 1)
    week_end = week_start + timedelta(days=7)
    weekly_minutes = _minutes(start_dt, end_dt, break_minutes)
    for row in existing_shifts:
        if (exclude_assignment_id is not None and row.get("assignment_id") == exclude_assignment_id) or row.get("status", row.get("assignment_status")) not in ACTIVE_ASSIGNMENT_STATUSES:
            continue
        old_start, old_end = _dt(row["start_date"]), _dt(row["end_date"])
        if old_start < end_dt and old_end > start_dt:
            conflicts.append({"code": "OVERLAP", "message": "Employee already has an overlapping shift"})
        elif 0 <= (start_dt - old_end).total_seconds() < min_rest_hours * 3600 or 0 <= (old_start - end_dt).total_seconds() < min_rest_hours * 3600:
            conflicts.append({"code": "INSUFFICIENT_REST", "message": f"Minimum {min_rest_hours} hours rest is required"})
        if week_start <= old_start.date() < week_end:
            weekly_minutes += _minutes(old_start, old_end, int(row.get("break_minutes") or 0))
    if weekly_minutes > max_weekly_minutes:
        conflicts.append({"code": "EXCESSIVE_WEEKLY_HOURS", "message": "Weekly scheduled work exceeds 48 hours"})
    leave_days = {str(item)[:10] for item in approved_leave_dates or []}
    if start_dt.date().isoformat() in leave_days:
        conflicts.append({"code": "APPROVED_LEAVE", "message": "Employee is on approved leave"})
    for row in weekly_offs or []:
        if int(row.get("day_of_week", 0)) == start_dt.isoweekday():
            conflicts.append({"code": "WEEKLY_OFF", "message": "Shift falls on the employee's weekly off"})
            break
    applicable = [r for r in availability or [] if int(r.get("day_of_week", 0)) == start_dt.isoweekday()]
    if applicable:
        start_t, end_t = start_dt.time().replace(tzinfo=None), end_dt.time().replace(tzinfo=None)
        if not any(r.get("is_available", True) and start_t >= datetime.strptime(r["available_start"][:5], "%H:%M").time()
                   and end_t <= datetime.strptime(r["available_end"][:5], "%H:%M").time() for r in applicable):
            conflicts.append({"code": "OUTSIDE_AVAILABILITY", "message": "Shift is outside employee availability"})
    # De-duplicate codes generated by adjacent shifts.
    unique = {item["code"]: item for item in conflicts}
    return {"valid": not unique, "conflicts": list(unique.values()), "weekly_minutes": weekly_minutes}


def whatsapp_shift_message(shift: dict, event: str = "PUBLISHED") -> str:
    start, end = _dt(shift["start_date"]), _dt(shift["end_date"])
    action = "published" if event == "PUBLISHED" else "updated"
    return (f"Your shift has been {action}: {start:%d %b %Y, %I:%M %p}–{end:%I:%M %p}, "
            f"{shift.get('property_name') or 'your property'} ({shift.get('role') or 'assigned role'}). "
            "Reply SHIFT for your roster. आपकी शिफ्ट अपडेट हो गई है।")


def send_shift_whatsapp(phone: str, shift: dict, event: str = "PUBLISHED") -> dict:
    # Keep deterministic validation importable in workers/tests without the
    # optional Twilio SDK; messaging is loaded only when publication needs it.
    from app.services.twilio_service import twilio_service
    return twilio_service.send_sms(to=phone, body=whatsapp_shift_message(shift, event), channel="whatsapp")
