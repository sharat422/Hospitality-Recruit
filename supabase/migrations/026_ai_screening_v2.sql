-- ─────────────────────────────────────────────────────────────────────────────
-- Extend candidates table
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE candidates
  ADD COLUMN IF NOT EXISTS screening_score      NUMERIC(5,2),
  ADD COLUMN IF NOT EXISTS auto_shortlisted     BOOLEAN DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS blind_id             TEXT,
  ADD COLUMN IF NOT EXISTS expected_salary_inr  INT,
  ADD COLUMN IF NOT EXISTS notice_period_days   INT DEFAULT 0,
  ADD COLUMN IF NOT EXISTS current_location     TEXT,
  ADD COLUMN IF NOT EXISTS preferred_location   TEXT,
  ADD COLUMN IF NOT EXISTS languages_spoken     TEXT[];

-- Unique blind_id per candidate (generated by service, stored here for reference)
CREATE INDEX IF NOT EXISTS idx_candidates_blind_id ON candidates(blind_id);
CREATE INDEX IF NOT EXISTS idx_candidates_screening_score ON candidates(screening_score DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- candidate_screening_results
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS candidate_screening_results (
  id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id                 UUID,
  job_id                 UUID,         -- references jobs(id) - Smart Recruitment
  job_role_id            UUID,         -- references job_roles(id) - legacy AI screening
  candidate_id           UUID NOT NULL,

  -- Composite score (weighted)
  total_score            NUMERIC(5,2)  NOT NULL DEFAULT 0,

  -- 6 scoring dimensions (0-100 each)
  skill_score            NUMERIC(5,2),
  experience_score       NUMERIC(5,2),
  language_score         NUMERIC(5,2),
  location_score         NUMERIC(5,2),
  salary_score           NUMERIC(5,2),
  availability_score     NUMERIC(5,2),

  -- HR-readable explanations per dimension
  skill_explanation      TEXT,
  experience_explanation TEXT,
  language_explanation   TEXT,
  location_explanation   TEXT,
  salary_explanation     TEXT,
  availability_explanation TEXT,

  -- Cross-industry matching
  cross_industry_match   BOOLEAN DEFAULT FALSE,
  cross_industry_source  TEXT,   -- e.g. 'retail', 'call_center', 'domestic_work'
  cross_industry_target  TEXT,   -- e.g. 'front_desk', 'housekeeping'
  cross_industry_boost   NUMERIC(5,2) DEFAULT 0,
  cross_industry_note    TEXT,

  -- Blind mode
  blind_id               TEXT,   -- deterministic anonymous ID, e.g. 'C-A3F7B2'
  blind_mode_used        BOOLEAN DEFAULT FALSE,

  -- Screening verdict
  overall_recommendation TEXT CHECK (overall_recommendation IN ('shortlist','consider','reject')),
  auto_shortlisted       BOOLEAN DEFAULT FALSE,
  shortlisted_at         TIMESTAMPTZ,

  -- Details
  strengths              TEXT[],
  gaps                   TEXT[],
  score_breakdown        JSONB,   -- full JSON payload from Claude

  -- Audit
  screened_at            TIMESTAMPTZ DEFAULT NOW(),
  screened_by            TEXT DEFAULT 'system',

  UNIQUE(job_id, candidate_id),
  UNIQUE(job_role_id, candidate_id)
);

CREATE INDEX IF NOT EXISTS idx_csr_job_id   ON candidate_screening_results(job_id);
CREATE INDEX IF NOT EXISTS idx_csr_role_id  ON candidate_screening_results(job_role_id);
CREATE INDEX IF NOT EXISTS idx_csr_total    ON candidate_screening_results(total_score DESC);
CREATE INDEX IF NOT EXISTS idx_csr_shortlist ON candidate_screening_results(auto_shortlisted);

-- ─────────────────────────────────────────────────────────────────────────────
-- screening_runs  — audit log for each screening batch
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS screening_runs (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id            UUID,
  job_id            UUID,
  job_role_id       UUID,
  triggered_by_user UUID,
  candidate_count   INT DEFAULT 0,
  shortlisted_count INT DEFAULT 0,
  blind_mode        BOOLEAN DEFAULT FALSE,
  screen_all        BOOLEAN DEFAULT FALSE,
  run_at            TIMESTAMPTZ DEFAULT NOW()
);

-- ─────────────────────────────────────────────────────────────────────────────
-- v_screening_leaderboard — ranked view joining candidates + jobs
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE VIEW v_screening_leaderboard AS
SELECT
  csr.id,
  csr.org_id,
  csr.job_id,
  csr.job_role_id,
  csr.candidate_id,
  csr.total_score,
  csr.skill_score,
  csr.experience_score,
  csr.language_score,
  csr.location_score,
  csr.salary_score,
  csr.availability_score,
  csr.skill_explanation,
  csr.experience_explanation,
  csr.language_explanation,
  csr.location_explanation,
  csr.salary_explanation,
  csr.availability_explanation,
  csr.cross_industry_match,
  csr.cross_industry_source,
  csr.cross_industry_target,
  csr.cross_industry_note,
  csr.blind_id,
  csr.blind_mode_used,
  csr.overall_recommendation,
  csr.auto_shortlisted,
  csr.shortlisted_at,
  csr.strengths,
  csr.gaps,
  csr.screened_at,
  -- Candidate identity (shown only in non-blind mode)
  c.first_name,
  c.last_name,
  c.email,
  c.phone,
  c.source,
  c.pipeline_status,
  c.years_experience,
  c.current_location AS candidate_location,
  c.expected_salary_inr,
  c.notice_period_days,
  -- Job details
  COALESCE(j.title, jr.title)               AS job_title,
  COALESCE(j.department, jr.department)     AS department,
  COALESCE(j.property_name, jr.location)   AS property_name,
  -- Rank within job
  RANK() OVER (
    PARTITION BY COALESCE(csr.job_id, csr.job_role_id)
    ORDER BY csr.total_score DESC
  ) AS rank
FROM candidate_screening_results csr
JOIN candidates c ON c.id = csr.candidate_id
LEFT JOIN jobs      j  ON j.id  = csr.job_id
LEFT JOIN job_roles jr ON jr.id = csr.job_role_id;
